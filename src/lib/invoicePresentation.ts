// ── Asal invoice ───────────────────────────────────────────────────────

export type InvoiceOrigin = "package" | "monthly" | "report" | "manual";
export type InvoiceOriginFilter = "semua" | InvoiceOrigin;

export function invoiceOriginOf(payment: Payment, report?: { billingMode?: string; autoGenerated?: boolean }): InvoiceOrigin {
  if (report?.billingMode === "session_count") return "package";
  if (report?.autoGenerated) return "monthly";
  if (payment.reportId) return "report";
  if (payment.source === "auto") return "monthly";
  return "manual";
}

